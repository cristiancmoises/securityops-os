def create_gate_job(
    *, gate_name: str, job_id: int, created_unix: int,
    expires_unix: int, challenge_nonce: str,
    owner_job_signer_fingerprint: str,
    result_signer_fingerprint: str, build_node_id: str,
    commands: Sequence[Mapping[str, Any]],
    prerequisite_receipt_digests: Sequence[str] = (),
    fixture_mode: bool = False,
) -> dict[str, Any]:
    if gate_name not in GATE_NAMES:
        raise PolicyError("unknown Phase 39 production gate")
    if type(job_id) is not int or job_id < 1:
        raise PolicyError("Phase 39 job ID is invalid")
    if (type(created_unix) is not int
            or type(expires_unix) is not int or created_unix < 1):
        raise PolicyError("Phase 39 job timestamps are invalid")
    if not (created_unix < expires_unix
            <= created_unix + MAX_JOB_LIFETIME_SECONDS):
        raise PolicyError("Phase 39 job lifetime is invalid")
    _sha256(challenge_nonce, "Phase 39 challenge")
    owner = _fingerprint(
        owner_job_signer_fingerprint, "Phase 39 owner signer")
    result_signer = _fingerprint(
        result_signer_fingerprint, "Phase 39 result signer")
    if (type(build_node_id) is not str
            or not _BUILD_NODE.fullmatch(build_node_id)):
        raise PolicyError("Phase 39 build-node identity is invalid")
    prereq_names = GATE_PREREQUISITES[gate_name]
    prereq_digests = [
        _sha256(item, "Phase 39 prerequisite receipt")
        for item in prerequisite_receipt_digests
    ]
    if len(prereq_digests) != len(prereq_names):
        raise PolicyError(
            "Phase 39 prerequisite receipt inventory is incomplete")
    if type(fixture_mode) is not bool:
        raise PolicyError("Phase 39 fixture flag is invalid")
    network_policy = GATE_NETWORK_POLICIES[gate_name]
    if (type(commands) not in {list, tuple}
            or not 1 <= len(commands) <= MAX_COMMANDS):
        raise PolicyError("Phase 39 command inventory is invalid")
    parsed_commands = [
        _parse_command(
            item, expected_sequence=index,
            network_policy=network_policy)
        for index, item in enumerate(commands, 1)
    ]
    gate_index = GATE_NAMES.index(gate_name) + 1
    unsigned: dict[str, Any] = {
        "format": JOB_FORMAT,
        "contract_digest": phase39_contract_digest(),
        "gate_name": gate_name,
        "gate_index": gate_index,
        "gate_requirements": list(GATE_REQUIREMENTS[gate_name]),
        "evidence_roles": list(GATE_EVIDENCE_ROLES[gate_name]),
        "prerequisite_gates": list(prereq_names),
        "prerequisite_receipt_digests": prereq_digests,
        "phase38_identities": dict(PHASE38_IDENTITIES),
        "phase38_contract_digest": PHASE38_CONTRACT_DIGEST,
        "job_id": job_id,
        "created_unix": created_unix,
        "expires_unix": expires_unix,
        "challenge_nonce": challenge_nonce,
        "owner_job_signer_fingerprint": owner,
        "result_signer_fingerprint": result_signer,
        "build_node_id": build_node_id,
        "network_policy": network_policy,
        "commands": parsed_commands,
        "fixture_mode": fixture_mode,
        "production_dispatch_allowed": False,
        "iso_release_allowed": False,
    }
    return {**unsigned, "job_digest": _digest(JOB_DOMAIN, unsigned)}


def parse_gate_job(
    value: Mapping[str, Any], *, now_unix: int | None = None,
) -> GateJob:
    expected_fields = set(gate_job_schema()["required"])
    if type(value) is not dict or set(value) != expected_fields:
        raise PolicyError("Phase 39 gate-job fields are not closed")
    candidate = json.loads(canonical_json_bytes(value))
    gate_name = candidate["gate_name"]
    if gate_name not in GATE_NAMES:
        raise PolicyError("unknown Phase 39 gate job")
    recreated = create_gate_job(
        gate_name=gate_name,
        job_id=candidate["job_id"],
        created_unix=candidate["created_unix"],
        expires_unix=candidate["expires_unix"],
        challenge_nonce=candidate["challenge_nonce"],
        owner_job_signer_fingerprint=
            candidate["owner_job_signer_fingerprint"],
        result_signer_fingerprint=candidate["result_signer_fingerprint"],
        build_node_id=candidate["build_node_id"],
        commands=candidate["commands"],
        prerequisite_receipt_digests=
            candidate["prerequisite_receipt_digests"],
        fixture_mode=candidate["fixture_mode"],
    )
    if candidate != recreated:
        raise PolicyError("Phase 39 gate-job identity or digest drifted")
    if now_unix is not None:
        if type(now_unix) is not int or now_unix < 1:
            raise PolicyError("Phase 39 verification time is invalid")
        if now_unix + MAX_CLOCK_SKEW_SECONDS < candidate["created_unix"]:
            raise PolicyError("Phase 39 gate job is from the future")
        if now_unix > candidate["expires_unix"] + MAX_CLOCK_SKEW_SECONDS:
            raise PolicyError("Phase 39 gate job expired")
    return GateJob(
        document=candidate,
        gate_name=gate_name,
        gate_index=candidate["gate_index"],
        job_id=candidate["job_id"],
        job_digest=candidate["job_digest"],
        owner_fingerprint=candidate["owner_job_signer_fingerprint"],
        result_fingerprint=candidate["result_signer_fingerprint"],
        fixture_mode=candidate["fixture_mode"],
    )


def _private_directory(path: Path, context: str) -> Path:
    candidate = path.absolute()
    if candidate.is_symlink():
        raise PolicyError(f"{context} cannot be a symbolic link")
    info = candidate.stat()
    if (not stat.S_ISDIR(info.st_mode)
            or stat.S_IMODE(info.st_mode) & 0o022
            or info.st_uid not in {0, os.getuid()}):
        raise PolicyError(f"{context} is not a private directory")
    return candidate


def _file_identity(info: os.stat_result) -> tuple[int, ...]:
    return (
        info.st_dev, info.st_ino, info.st_mode, info.st_uid,
        info.st_gid, info.st_nlink, info.st_size, info.st_mtime_ns,
        info.st_ctime_ns,
    )


def _measure_relative_file(
    *, root: Path, filename: str, maximum: int, allow_empty: bool,
) -> dict[str, Any]:
    root = _private_directory(root, "Phase 39 evidence root")
    filename = _token(filename, "Phase 39 evidence filename")
    root_fd = os.open(
        root,
        os.O_RDONLY | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_CLOEXEC", 0),
    )
    try:
        fd = os.open(
            filename,
            os.O_RDONLY | getattr(os, "O_CLOEXEC", 0)
            | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=root_fd,
        )
    except OSError as exc:
        os.close(root_fd)
        raise PolicyError(
            f"Phase 39 evidence file is unavailable: {filename}") from exc
    try:
        before = os.fstat(fd)
        mode = stat.S_IMODE(before.st_mode)
        minimum = 0 if allow_empty else 1
        if (not stat.S_ISREG(before.st_mode)
                or before.st_nlink != 1
                or not minimum <= before.st_size <= maximum
                or mode & 0o022
                or before.st_uid not in {0, os.getuid()}):
            raise PolicyError(
                f"unsafe Phase 39 evidence file: {filename}")
        digest = hashlib.sha256()
        remaining = before.st_size
        while remaining:
            block = os.read(fd, min(1024 * 1024, remaining))
            if not block:
                raise PolicyError(
                    f"Phase 39 evidence file was truncated: {filename}")
            digest.update(block)
            remaining -= len(block)
        if os.read(fd, 1):
            raise PolicyError(
                f"Phase 39 evidence file grew while measured: {filename}")
        after = os.fstat(fd)
        if _file_identity(before) != _file_identity(after):
            raise PolicyError(
                f"Phase 39 evidence file changed while measured: {filename}")
        return {
            "bytes": before.st_size,
            "sha256": digest.hexdigest(),
            "mode": mode,
            "executable": bool(mode & 0o111),
            "device": before.st_dev,
            "inode": before.st_ino,
        }
    finally:
        os.close(fd)
        os.close(root_fd)


def make_command_transcript(
    *, command: Mapping[str, Any], started_unix: int,
    finished_unix: int, returncode: int, stdout_filename: str,
    stderr_filename: str, evidence_root: Path,
    timed_out: bool = False, output_limited: bool = False,
) -> dict[str, Any]:
    if (type(started_unix) is not int
            or type(finished_unix) is not int or started_unix < 1
            or finished_unix < started_unix):
        raise PolicyError("Phase 39 transcript timestamps are invalid")
    if type(returncode) is not int or not -255 <= returncode <= 255:
        raise PolicyError("Phase 39 transcript return code is invalid")
    if type(timed_out) is not bool or type(output_limited) is not bool:
        raise PolicyError("Phase 39 transcript status flags are invalid")
    sequence = command.get("sequence")
    command_digest = command.get("command_digest")
    if (type(sequence) is not int
            or type(command_digest) is not str
            or not _HEX64.fullmatch(command_digest)):
        raise PolicyError(
            "Phase 39 transcript command identity is invalid")
    out = _measure_relative_file(
        root=evidence_root, filename=stdout_filename,
        maximum=MAX_LOG_BYTES, allow_empty=True)
    err = _measure_relative_file(
        root=evidence_root, filename=stderr_filename,
        maximum=MAX_LOG_BYTES, allow_empty=True)
    return {
        "sequence": sequence,
        "command_digest": command_digest,
        "started_unix": started_unix,
        "finished_unix": finished_unix,
        "returncode": returncode,
        "timed_out": timed_out,
        "output_limited": output_limited,
        "stdout_filename": _token(
            stdout_filename, "Phase 39 stdout filename"),
        "stdout_bytes": out["bytes"],
        "stdout_sha256": out["sha256"],
        "stderr_filename": _token(
            stderr_filename, "Phase 39 stderr filename"),
        "stderr_bytes": err["bytes"],
        "stderr_sha256": err["sha256"],
    }


def measure_evidence_record(
    *, evidence_root: Path, role: str, filename: str, kind: str,
    command_digest: str, fixture: bool, build_id: str = "",
    store_path: str = "",
) -> dict[str, Any]:
    allowed_roles = {
        role for roles in GATE_EVIDENCE_ROLES.values() for role in roles
    }
    if role not in allowed_roles:
        raise PolicyError("unknown Phase 39 evidence role")
    if kind not in EVIDENCE_KINDS:
        raise PolicyError("unknown Phase 39 evidence kind")
    _sha256(command_digest, "Phase 39 evidence command")
    if type(fixture) is not bool:
        raise PolicyError("Phase 39 evidence fixture flag is invalid")
    if (type(build_id) is not str or len(build_id) > 256
            or any(ord(ch) < 32 for ch in build_id)):
        raise PolicyError("Phase 39 evidence build ID is invalid")
    if (type(store_path) is not str or len(store_path) > 4096
            or "\x00" in store_path):
        raise PolicyError("Phase 39 evidence Store path is invalid")
    measured = _measure_relative_file(
        root=evidence_root, filename=filename,
        maximum=MAX_EVIDENCE_BYTES, allow_empty=False)
    return {
        "role": role,
        "filename": _token(filename, "Phase 39 evidence filename"),
        "kind": kind,
        "bytes": measured["bytes"],
        "sha256": measured["sha256"],
        "mode": measured["mode"],
        "executable": measured["executable"],
        "command_digest": command_digest,
        "build_id": build_id,
        "store_path": store_path,
        "measurement_scope": "descriptor-bound",
        "contains_secrets": False,
        "fixture": fixture,
    }


def _parse_transcript(
    value: Mapping[str, Any], *, command: Mapping[str, Any],
    evidence_root: Path,
) -> dict[str, Any]:
    required = set(
        gate_result_schema()["properties"]["command_transcripts"]
        ["items"]["required"]
    )
    if type(value) is not dict or set(value) != required:
        raise PolicyError(
            "Phase 39 command-transcript fields are not closed")
    expected = make_command_transcript(
        command=command,
        started_unix=value["started_unix"],
        finished_unix=value["finished_unix"],
        returncode=value["returncode"],
        stdout_filename=value["stdout_filename"],
        stderr_filename=value["stderr_filename"],
        evidence_root=evidence_root,
        timed_out=value["timed_out"],
        output_limited=value["output_limited"],
    )
    if value != expected:
        raise PolicyError(
            "Phase 39 command transcript differs from measured logs")
    return expected


def _parse_evidence_record(
    value: Mapping[str, Any], *, expected_role: str, job: GateJob,
    evidence_root: Path,
) -> dict[str, Any]:
    required = set(
        gate_result_schema()["properties"]["evidence"]
        ["items"]["required"]
    )
    if type(value) is not dict or set(value) != required:
        raise PolicyError("Phase 39 evidence-record fields are not closed")
    if value["role"] != expected_role:
        raise PolicyError("Phase 39 evidence role order drifted")
    command_digests = {
        item["command_digest"] for item in job.document["commands"]
    }
    if value["command_digest"] not in command_digests:
        raise PolicyError(
            "Phase 39 evidence refers to an unknown command")
    expected = measure_evidence_record(
        evidence_root=evidence_root,
        role=expected_role,
        filename=value["filename"],
        kind=value["kind"],
        command_digest=value["command_digest"],
        fixture=value["fixture"],
        build_id=value["build_id"],
        store_path=value["store_path"],
    )
    if value != expected:
        raise PolicyError(
            "Phase 39 evidence record differs from local remeasurement")
    if value["fixture"] != job.fixture_mode:
        raise PolicyError(
            "Phase 39 evidence fixture identity differs from the job")
    store_roles = {
        "guix-store-toolchain", "guix-center-build-a",
        "guix-center-build-b", "store-closure",
        "kernel-build-a", "kernel-build-b",
    }
    if (not job.fixture_mode and expected_role in store_roles
            and not value["store_path"].startswith("/gnu/store/")):
        raise PolicyError(
            "Phase 39 production Guix evidence is not bound to the Store")
    return expected


def create_gate_result(
    *, job_document: Mapping[str, Any], evidence_root: Path,
    signer_fingerprint: str, started_unix: int, finished_unix: int,
    host_attestation_digest: str,
    command_transcripts: Sequence[Mapping[str, Any]],
    evidence_records: Sequence[Mapping[str, Any]], gate_state: str,
    requirements_satisfied: bool, fixture_mode: bool,
    iso_bytes_present: bool = False,
) -> dict[str, Any]:
    job = parse_gate_job(job_document)
    signer = _fingerprint(
        signer_fingerprint, "Phase 39 result signer")
    if signer != job.result_fingerprint:
        raise PolicyError(
            "Phase 39 result signer differs from the signed job")
    if (type(started_unix) is not int
            or type(finished_unix) is not int
            or started_unix < job.document["created_unix"]
            or finished_unix < started_unix):
        raise PolicyError("Phase 39 result timestamps are invalid")
    _sha256(host_attestation_digest, "Phase 39 host attestation")
    if gate_state not in RESULT_STATES:
        raise PolicyError("Phase 39 gate-result state is invalid")
    if (type(requirements_satisfied) is not bool
            or type(fixture_mode) is not bool
            or type(iso_bytes_present) is not bool):
        raise PolicyError("Phase 39 result Boolean is invalid")
    if fixture_mode != job.fixture_mode:
        raise PolicyError(
            "Phase 39 result fixture state differs from the job")
    if requirements_satisfied != (gate_state == "passed"):
        raise PolicyError(
            "Phase 39 result state and requirement status conflict")
    if (iso_bytes_present
            and (job.gate_name != "reproducible-iso-build-and-boot"
                 or fixture_mode or gate_state != "passed")):
        raise PolicyError(
            "Phase 39 ISO bytes were claimed outside the exact ISO gate")
    if (type(command_transcripts) not in {list, tuple}
            or len(command_transcripts) != len(job.document["commands"])):
        raise PolicyError(
            "Phase 39 command-transcript inventory is incomplete")
    parsed_transcripts = [
        _parse_transcript(
            item, command=command, evidence_root=evidence_root)
        for item, command in zip(
            command_transcripts, job.document["commands"], strict=True)
    ]
    if gate_state == "passed" and any(
        item["returncode"] != 0
        or item["timed_out"]
        or item["output_limited"]
        for item in parsed_transcripts
    ):
        raise PolicyError(
            "Phase 39 passing result contains an unsuccessful command")
    roles = GATE_EVIDENCE_ROLES[job.gate_name]
    if (type(evidence_records) not in {list, tuple}
            or len(evidence_records) != len(roles)):
        raise PolicyError("Phase 39 evidence inventory is incomplete")
    parsed_evidence = [
        _parse_evidence_record(
            item, expected_role=role, job=job,
            evidence_root=evidence_root)
        for item, role in zip(evidence_records, roles, strict=True)
    ]
    filenames = [item["filename"] for item in parsed_evidence]
    log_filenames = [
        name for item in parsed_transcripts
        for name in (item["stdout_filename"], item["stderr_filename"])
    ]
    if len(set(filenames + log_filenames)) != len(
            filenames + log_filenames):
        raise PolicyError(
            "Phase 39 result reuses an evidence or log filename")
    unsigned: dict[str, Any] = {
        "format": RESULT_FORMAT,
        "contract_digest": phase39_contract_digest(),
        "job_digest": job.job_digest,
        "gate_name": job.gate_name,
        "gate_index": job.gate_index,
        "job_id": job.job_id,
        "challenge_nonce": job.document["challenge_nonce"],
        "started_unix": started_unix,
        "finished_unix": finished_unix,
        "signer_fingerprint": signer,
        "host_attestation_digest": host_attestation_digest,
        "prerequisite_receipt_digests":
            list(job.document["prerequisite_receipt_digests"]),
        "command_transcripts": parsed_transcripts,
        "evidence": parsed_evidence,
        "gate_state": gate_state,
        "requirements_satisfied": requirements_satisfied,
        "fixture_mode": fixture_mode,
        "production_gate_approved": False,
        "production_dispatch_allowed": False,
        "iso_release_allowed": False,
        "iso_bytes_present": iso_bytes_present,
    }
    return {**unsigned, "result_digest": _digest(RESULT_DOMAIN, unsigned)}


def parse_gate_result(
    value: Mapping[str, Any], *, job: GateJob, evidence_root: Path,
) -> GateResult:
    expected_fields = set(gate_result_schema()["required"])
    if type(value) is not dict or set(value) != expected_fields:
        raise PolicyError("Phase 39 gate-result fields are not closed")
    candidate = json.loads(canonical_json_bytes(value))
    recreated = create_gate_result(
        job_document=job.document,
        evidence_root=evidence_root,
        signer_fingerprint=candidate["signer_fingerprint"],
        started_unix=candidate["started_unix"],
        finished_unix=candidate["finished_unix"],
        host_attestation_digest=candidate["host_attestation_digest"],
        command_transcripts=candidate["command_transcripts"],
        evidence_records=candidate["evidence"],
        gate_state=candidate["gate_state"],
        requirements_satisfied=candidate["requirements_satisfied"],
        fixture_mode=candidate["fixture_mode"],
        iso_bytes_present=candidate["iso_bytes_present"],
    )
    if candidate != recreated:
        raise PolicyError(
            "Phase 39 gate-result identity or digest drifted")
    if (candidate["finished_unix"]
            > job.document["expires_unix"] + MAX_CLOCK_SKEW_SECONDS):
        raise PolicyError(
            "Phase 39 result completed after the signed job expired")
    return GateResult(
        document=candidate,
        result_digest=candidate["result_digest"],
        gate_name=candidate["gate_name"],
        state=candidate["gate_state"],
        fixture_mode=candidate["fixture_mode"],
        iso_bytes_present=candidate["iso_bytes_present"],
    )


def _strict_json_bytes(payload: bytes, context: str) -> dict[str, Any]:
    def pairs(items: Sequence[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, value in items:
            if key in result:
                raise PolicyError(f"duplicate {context} field: {key}")
            result[key] = value
        return result

    def constant(value: str) -> None:
        raise PolicyError(f"non-finite value in {context}: {value}")

    try:
        value = json.loads(
            payload.decode("utf-8", errors="strict"),
            object_pairs_hook=pairs, parse_constant=constant)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise PolicyError(f"invalid {context} JSON") from exc
    if type(value) is not dict:
        raise PolicyError(f"{context} must be a JSON object")
    return value


def _measure_signed_input(
    path: Path, *, maximum: int, role: str,
) -> tuple[dict[str, Any], bytes]:
    candidate = path.absolute()
    if candidate.is_symlink():
        raise PolicyError(
            f"symbolic Phase 39 signed input rejected: {role}")
    flags = (
        os.O_RDONLY | getattr(os, "O_CLOEXEC", 0)
        | getattr(os, "O_NOFOLLOW", 0)
    )
    try:
        fd = os.open(candidate, flags)
    except OSError as exc:
        raise PolicyError(
            f"required Phase 39 signed input unavailable: {role}") from exc
    try:
        before = os.fstat(fd)
        mode = stat.S_IMODE(before.st_mode)
        if (not stat.S_ISREG(before.st_mode)
                or before.st_nlink != 1
                or not 1 <= before.st_size <= maximum
                or mode & 0o022
                or before.st_uid not in {0, os.getuid()}):
            raise PolicyError(f"unsafe Phase 39 signed input: {role}")
        payload = bytearray()
        remaining = before.st_size
        while remaining:
            block = os.read(fd, min(1024 * 1024, remaining))
            if not block:
                raise PolicyError(
                    f"Phase 39 signed input was truncated: {role}")
            payload.extend(block)
            remaining -= len(block)
        if os.read(fd, 1):
            raise PolicyError(
                f"Phase 39 signed input grew while measured: {role}")
        after = os.fstat(fd)
        if _file_identity(before) != _file_identity(after):
            raise PolicyError(
                f"Phase 39 signed input changed while measured: {role}")
    finally:
        os.close(fd)
    data = bytes(payload)
    return {
        "role": role,
        "sha256": hashlib.sha256(data).hexdigest(),
        "bytes": len(data),
        "device": after.st_dev,
        "inode": after.st_ino,
    }, data


def _sealed_memfd(name: str, payload: bytes) -> int:
    _token(name, "Phase 39 memfd name")
    required_os = ("memfd_create", "MFD_CLOEXEC", "MFD_ALLOW_SEALING")
    required_fcntl = (
        "F_ADD_SEALS", "F_GET_SEALS", "F_SEAL_SEAL",
        "F_SEAL_SHRINK", "F_SEAL_GROW", "F_SEAL_WRITE",
    )
    if (any(not hasattr(os, item) for item in required_os)
            or any(not hasattr(fcntl, item) for item in required_fcntl)):
        raise PolicyError(
            "Linux memfd sealing is required for Phase 39 verification")
    fd = os.memfd_create(
        f"phase39-{name}",
        flags=os.MFD_CLOEXEC | os.MFD_ALLOW_SEALING)
    try:
        os.fchmod(fd, 0o400)
        view = memoryview(payload)
        while view:
            written = os.write(fd, view)
            if written <= 0:
                raise PolicyError(
                    "unable to write Phase 39 sealed signature input")
            view = view[written:]
        os.fsync(fd)
        os.lseek(fd, 0, os.SEEK_SET)
        seals = (
            fcntl.F_SEAL_SEAL | fcntl.F_SEAL_SHRINK
            | fcntl.F_SEAL_GROW | fcntl.F_SEAL_WRITE
        )
        fcntl.fcntl(fd, fcntl.F_ADD_SEALS, seals)
        observed = os.fstat(fd)
        observed_seals = fcntl.fcntl(fd, fcntl.F_GET_SEALS)
        if (not stat.S_ISREG(observed.st_mode)
                or observed.st_size != len(payload)
                or stat.S_IMODE(observed.st_mode) != 0o400
                or observed_seals & seals != seals):
            raise PolicyError(
                "Phase 39 sealed signature input identity drifted")
        return fd
    except Exception:
        os.close(fd)
        raise


def _safe_gpgv(path: str | Path, *, fixture_mode: bool) -> str:
    candidate = Path(path)
    if not candidate.is_absolute() or candidate.is_symlink():
        raise PolicyError(
            "Phase 39 gpgv executable must be an absolute regular file")
    info = candidate.stat()
    if (not stat.S_ISREG(info.st_mode)
            or not os.access(candidate, os.X_OK)
            or stat.S_IMODE(info.st_mode) & 0o022):
        raise PolicyError("Phase 39 gpgv executable identity is unsafe")
    resolved = candidate.resolve(strict=True)
    if (not fixture_mode
            and resolved != Path("/usr/bin/gpgv").resolve(strict=True)):
        raise PolicyError(
            "non-fixture Phase 39 verification requires /usr/bin/gpgv")
    return os.fspath(resolved)


def _validsig(status: bytes, expected: str, role: str) -> None:
    observed: list[str] = []
    for line in status.decode("utf-8", errors="strict").splitlines():
        if line.startswith("[GNUPG:] VALIDSIG "):
            fields = line.split()
            if len(fields) >= 3:
                observed.append(fields[2])
    if observed != [expected]:
        raise PolicyError(
            f"gpgv did not produce exactly one admitted "
            f"Phase 39 {role} VALIDSIG")


def _verify_signature(
    *, payload: bytes, signature: bytes, keyring: bytes,
    expected_fingerprint: str, gpgv_executable: str | Path,
    fixture_mode: bool, role: str,
) -> None:
    gpgv = _safe_gpgv(gpgv_executable, fixture_mode=fixture_mode)
    fds: list[int] = []
    try:
        payload_fd = _sealed_memfd(f"{role}-payload", payload)
        signature_fd = _sealed_memfd(f"{role}-signature", signature)
        keyring_fd = _sealed_memfd(f"{role}-keyring", keyring)
        fds.extend((payload_fd, signature_fd, keyring_fd))
        completed = subprocess.run(
            [
                gpgv, "--status-fd", "1", "--keyring",
                f"/proc/self/fd/{keyring_fd}",
                f"/proc/self/fd/{signature_fd}",
                f"/proc/self/fd/{payload_fd}",
            ],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
            timeout=30,
            close_fds=True,
            pass_fds=tuple(fds),
            env={
                "PATH": "/usr/bin:/bin",
                "LANG": "C", "LC_ALL": "C",
                "GNUPGHOME": "/nonexistent",
            },
        )
        if completed.returncode != 0:
            raise PolicyError(
                f"gpgv rejected the Phase 39 {role} signature")
        _validsig(completed.stdout, expected_fingerprint, role)
    except subprocess.SubprocessError as exc:
        raise PolicyError(
            f"Phase 39 {role} signature verification did not complete"
        ) from exc
    finally:
        for fd in reversed(fds):
            try:
                os.close(fd)
            except OSError:
                pass


def _ledger_empty() -> dict[str, Any]:
    unsigned = {
        "format": LEDGER_FORMAT,
        "highest_job_id": 0,
        "seen_job_digests": [],
        "seen_result_digests": [],
        "generation": 0,
    }
    return {
        **unsigned,
        "ledger_digest": _digest(LEDGER_DOMAIN, unsigned),
    }


def _load_ledger(path: Path) -> dict[str, Any]:
    if not path.exists():
        return _ledger_empty()
    _private_directory(
        path.parent, "Phase 39 replay-ledger directory")
    _, payload = _measure_signed_input(
        path, maximum=2 * 1024 * 1024, role="replay-ledger")
    value = _strict_json_bytes(payload, "Phase 39 replay ledger")
    fields = {
        "format", "highest_job_id", "seen_job_digests",
        "seen_result_digests", "generation", "ledger_digest",
    }
    if set(value) != fields or value["format"] != LEDGER_FORMAT:
        raise PolicyError("Phase 39 replay ledger schema is invalid")
    if (type(value["highest_job_id"]) is not int
            or value["highest_job_id"] < 0
            or type(value["generation"]) is not int
            or value["generation"] < 0):
        raise PolicyError("Phase 39 replay ledger counters are invalid")
    for name in ("seen_job_digests", "seen_result_digests"):
        items = value[name]
        if (type(items) is not list
                or len(items) > MAX_LEDGER_ENTRIES
                or len(set(items)) != len(items)
                or any(type(item) is not str
                       or not _HEX64.fullmatch(item) for item in items)):
            raise PolicyError(
                "Phase 39 replay ledger digest inventory is invalid")
    unsigned = {
        key: value[key] for key in value if key != "ledger_digest"
    }
    if value["ledger_digest"] != _digest(LEDGER_DOMAIN, unsigned):
        raise PolicyError("Phase 39 replay ledger digest mismatch")
    return value


def _write_ledger(path: Path, value: Mapping[str, Any]) -> None:
    parent = path.parent
    parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(parent, 0o700)
    _private_directory(
        parent, "Phase 39 replay-ledger directory")
    if path.exists() and path.is_symlink():
        raise PolicyError(
            "Phase 39 replay ledger cannot be a symbolic link")
    payload = canonical_json_bytes(value) + b"\n"
    fd, raw = tempfile.mkstemp(prefix=".phase39-ledger-", dir=parent)
    temporary = Path(raw)
    try:
        os.fchmod(fd, 0o600)
        view = memoryview(payload)
        while view:
            written = os.write(fd, view)
            if written <= 0:
                raise PolicyError(
                    "unable to write Phase 39 replay ledger")
            view = view[written:]
        os.fsync(fd)
        os.close(fd)
        fd = -1
        os.replace(temporary, path)
        directory_fd = os.open(
            parent, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0))
        try:
            os.fsync(directory_fd)
        finally:
            os.close(directory_fd)
    finally:
        if fd >= 0:
            os.close(fd)
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass


def _record_once(
    path: Path, *, job_id: int, job_digest: str, result_digest: str,
) -> None:
    parent = path.parent
    parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    os.chmod(parent, 0o700)
    lock_path = parent / ".phase39-replay.lock"
    lock_fd = os.open(
        lock_path,
        os.O_RDWR | os.O_CREAT | getattr(os, "O_CLOEXEC", 0)
        | getattr(os, "O_NOFOLLOW", 0),
        0o600,
    )
    try:
        info = os.fstat(lock_fd)
        if (not stat.S_ISREG(info.st_mode)
                or info.st_nlink != 1
                or stat.S_IMODE(info.st_mode) & 0o077):
            raise PolicyError(
                "unsafe Phase 39 replay-ledger lock")
        fcntl.flock(lock_fd, fcntl.LOCK_EX)
        value = _load_ledger(path)
        if (job_id <= value["highest_job_id"]
                or job_digest in value["seen_job_digests"]
                or result_digest in value["seen_result_digests"]):
            raise PolicyError(
                "Phase 39 replay or non-monotonic job rejected")
        seen_jobs = (
            value["seen_job_digests"] + [job_digest]
        )[-MAX_LEDGER_ENTRIES:]
        seen_results = (
            value["seen_result_digests"] + [result_digest]
        )[-MAX_LEDGER_ENTRIES:]
        unsigned = {
            "format": LEDGER_FORMAT,
            "highest_job_id": job_id,
            "seen_job_digests": seen_jobs,
            "seen_result_digests": seen_results,
            "generation": value["generation"] + 1,
        }
        _write_ledger(
            path,
            {
                **unsigned,
                "ledger_digest": _digest(LEDGER_DOMAIN, unsigned),
            },
        )
    finally:
        try:
            fcntl.flock(lock_fd, fcntl.LOCK_UN)
        finally:
            os.close(lock_fd)


def verify_signed_gate_exchange(
    *, job_path: Path, job_signature_path: Path,
    owner_keyring_path: Path, result_path: Path,
    result_signature_path: Path, result_keyring_path: Path,
    evidence_root: Path, replay_ledger_path: Path,
    expected_owner_fingerprint: str, now_unix: int,
    gpgv_executable: str | Path = "/usr/bin/gpgv",
) -> VerifiedGateExchange:
    expected_owner = _fingerprint(
        expected_owner_fingerprint,
        "Phase 39 locally pinned owner signer")
    job_meta, job_bytes = _measure_signed_input(
        job_path, maximum=MAX_JOB_BYTES, role="signed-job")
    job_sig_meta, job_signature = _measure_signed_input(
        job_signature_path,
        maximum=MAX_SIGNATURE_BYTES, role="job-signature")
    owner_key_meta, owner_key = _measure_signed_input(
        owner_keyring_path,
        maximum=MAX_KEYRING_BYTES, role="owner-keyring")
    job_document = _strict_json_bytes(
        job_bytes, "Phase 39 gate job")
    job = parse_gate_job(job_document, now_unix=now_unix)
    if job.owner_fingerprint != expected_owner:
        raise PolicyError(
            "Phase 39 job owner fingerprint differs from local trust policy")
    _verify_signature(
        payload=job_bytes,
        signature=job_signature,
        keyring=owner_key,
        expected_fingerprint=expected_owner,
        gpgv_executable=gpgv_executable,
        fixture_mode=job.fixture_mode,
        role="owner-job",
    )

    result_meta, result_bytes = _measure_signed_input(
        result_path, maximum=MAX_RESULT_BYTES, role="signed-result")
    result_sig_meta, result_signature = _measure_signed_input(
        result_signature_path,
        maximum=MAX_SIGNATURE_BYTES, role="result-signature")
    result_key_meta, result_key = _measure_signed_input(
        result_keyring_path,
        maximum=MAX_KEYRING_BYTES, role="result-keyring")
    _verify_signature(
        payload=result_bytes,
        signature=result_signature,
        keyring=result_key,
        expected_fingerprint=job.result_fingerprint,
        gpgv_executable=gpgv_executable,
        fixture_mode=job.fixture_mode,
        role="build-node-result",
    )
    result_document = _strict_json_bytes(
        result_bytes, "Phase 39 gate result")
    result = parse_gate_result(
        result_document, job=job, evidence_root=evidence_root)
    if now_unix + MAX_CLOCK_SKEW_SECONDS < result.document["finished_unix"]:
        raise PolicyError(
            "Phase 39 result completion is from the future")
    _record_once(
        replay_ledger_path, job_id=job.job_id,
        job_digest=job.job_digest,
        result_digest=result.result_digest)

    owner_authenticated = not job.fixture_mode
    gate_approved = bool(
        owner_authenticated
        and result.state == "passed"
        and result.document["requirements_satisfied"]
        and all(
            item["returncode"] == 0
            and not item["timed_out"]
            and not item["output_limited"]
            for item in result.document["command_transcripts"]
        )
        and all(
            not item["fixture"] for item in result.document["evidence"]
        )
    )
    signed = {
        "job": job_meta["sha256"],
        "job-signature": job_sig_meta["sha256"],
        "owner-keyring": owner_key_meta["sha256"],
        "result": result_meta["sha256"],
        "result-signature": result_sig_meta["sha256"],
        "result-keyring": result_key_meta["sha256"],
    }
    unsigned = {
        "format": VERIFICATION_FORMAT,
        "gate_name": job.gate_name,
        "gate_index": job.gate_index,
        "job_id": job.job_id,
        "job_digest": job.job_digest,
        "result_digest": result.result_digest,
        "owner_signature_verified": True,
        "result_signature_verified": True,
        "evidence_inventory_verified": True,
        "replay_ledger_updated": True,
        "fixture_mode": job.fixture_mode,
        "owner_authenticated": owner_authenticated,
        "gate_approved": gate_approved,
        "prerequisite_receipt_digests":
            list(job.document["prerequisite_receipt_digests"]),
        "iso_bytes_present": result.iso_bytes_present,
        "signed_input_sha256": signed,
    }
    verification_digest = _digest(
        VERIFICATION_DOMAIN, unsigned)
    return VerifiedGateExchange(
        gate_name=job.gate_name,
        gate_index=job.gate_index,
        job_id=job.job_id,
        job_digest=job.job_digest,
        result_digest=result.result_digest,
        owner_signature_verified=True,
        result_signature_verified=True,
        evidence_inventory_verified=True,
        replay_ledger_updated=True,
        fixture_mode=job.fixture_mode,
        owner_authenticated=owner_authenticated,
        gate_approved=gate_approved,
        prerequisite_receipt_digests=tuple(
            job.document["prerequisite_receipt_digests"]),
        iso_bytes_present=result.iso_bytes_present,
        signed_input_sha256=signed,
        verification_digest=verification_digest,
    )


def evaluate_gate_verifications(
    verifications: Sequence[VerifiedGateExchange],
) -> dict[str, Any]:
    by_name: dict[str, VerifiedGateExchange] = {}
    for item in verifications:
        if (not isinstance(item, VerifiedGateExchange)
                or item.gate_name in by_name):
            raise PolicyError(
                "Phase 39 gate-verification inventory is invalid")
        if item.gate_index != GATE_NAMES.index(item.gate_name) + 1:
            raise PolicyError(
                "Phase 39 gate-verification index drifted")
        by_name[item.gate_name] = item
    passed: list[str] = []
    blocked: list[str] = []
    receipts: dict[str, str] = {}
    gates: list[dict[str, Any]] = []
    for spec in phase38.GATE_SPECS:
        item = by_name.get(spec.name)
        prereq_digests = tuple(
            receipts[name] for name in spec.prerequisites
            if name in receipts)
        prereq_complete = (
            len(prereq_digests) == len(spec.prerequisites))
        approved = bool(
            item is not None
            and item.owner_signature_verified
            and item.result_signature_verified
            and item.evidence_inventory_verified
            and item.replay_ledger_updated
            and item.owner_authenticated
            and not item.fixture_mode
            and item.gate_approved
            and prereq_complete
            and item.prerequisite_receipt_digests == prereq_digests
        )
        if approved:
            passed.append(spec.name)
            receipts[spec.name] = item.verification_digest
            state = "passed"
            blocker = ""
        else:
            blocked.append(spec.name)
            state = "blocked"
            blocker = (
                "BLOCKED_PHASE39_OWNER_SIGNED_"
                + spec.name.upper().replace("-", "_")
                + "_RECEIPT_REQUIRED"
            )
        gates.append({
            "name": spec.name,
            "state": state,
            "prerequisites": list(spec.prerequisites),
            "verification_digest":
                "" if item is None else item.verification_digest,
            "gate_approved": approved,
            "blocker": blocker,
        })
    all_passed = len(passed) == len(GATE_NAMES)
    iso_item = by_name.get(
        "reproducible-iso-build-and-boot")
    iso_bytes_present = bool(
        all_passed and iso_item is not None
        and iso_item.iso_bytes_present)
    unsigned = {
        "format": EVALUATION_FORMAT,
        "status": STATUS if all_passed else BLOCKED_STATUS,
        "phase39_contract_digest": phase39_contract_digest(),
        "gates": gates,
        "passed_gate_names": passed,
        "blocked_gate_names": blocked,
        "production_gates_approved": len(passed),
        "production_dispatch_allowed": all_passed,
        "iso_release_allowed": bool(
            all_passed and iso_bytes_present),
        "iso_bytes_present": iso_bytes_present,
        "release_decision":
            "RELEASE READY"
            if all_passed and iso_bytes_present
            else "NOT RELEASE READY — BLOCKERS LISTED",
    }
    return {
        **unsigned,
        "evaluation_digest": _digest(EVALUATION_DOMAIN, unsigned),
    }


def run_phase39_negative_matrix() -> dict[str, Any]:
    contract = phase39_contract()
    mutations = (
        lambda value: value["signature_boundary"].__setitem__(
            "owner_job_signature_required", False),
        lambda value: value["signature_boundary"].__setitem__(
            "build_node_result_signature_required", False),
        lambda value: value["signature_boundary"].__setitem__(
            "exact_fingerprints_required", False),
        lambda value: value["signature_boundary"].__setitem__(
            "signature_verification_uses_kernel_sealed_memfd", False),
        lambda value: value["signature_boundary"].__setitem__(
            "original_paths_reopened_by_gpgv", True),
        lambda value: value["signature_boundary"].__setitem__(
            "monotonic_replay_ledger_required", False),
        lambda value: value["execution_boundary"].__setitem__(
            "shell_allowed", True),
        lambda value: value["execution_boundary"].__setitem__(
            "evidence_remeasurement_required", False),
        lambda value: value["execution_boundary"].__setitem__(
            "logs_remeasurement_required", False),
        lambda value: value["execution_boundary"].__setitem__(
            "fixture_can_promote_gate", True),
        lambda value: value["truth_boundary"].__setitem__(
            "tcg_is_kvm", True),
        lambda value: value["truth_boundary"].__setitem__(
            "af_unix_is_af_vsock", True),
        lambda value: value["truth_boundary"].__setitem__(
            "archive_is_bootable_iso", True),
        lambda value: value["gate_order"].reverse(),
        lambda value: value["gate_evidence_roles"].pop(GATE_NAMES[0]),
        lambda value: value["gate_network_policies"].__setitem__(
            GATE_NAMES[1], "outbound-allowlisted"),
        lambda value: value["blockers"].pop(),
        lambda value: value.__setitem__(
            "production_gates_approved", 1),
        lambda value: value.__setitem__(
            "production_dispatch_allowed", True),
        lambda value: value.__setitem__(
            "iso_release_allowed", True),
    )
    rejected = 0
    for mutate in mutations:
        candidate = json.loads(json.dumps(contract))
        mutate(candidate)
        try:
            parse_phase39_contract(candidate)
        except PolicyError:
            rejected += 1
    return {
        "format": "securityops-phase39-negative-matrix/1",
        "case_count": len(mutations),
        "rejected_count": rejected,
        "all_rejected": rejected == len(mutations),
    }


