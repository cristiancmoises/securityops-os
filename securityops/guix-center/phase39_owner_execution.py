def phase39_selftest() -> dict[str, Any]:
    contract = phase39_contract()
    parse_phase39_contract(contract)
    negative = run_phase39_negative_matrix()
    if not negative["all_rejected"]:
        raise AssertionError(
            "Phase 39 contract self-test accepted a downgrade")
    observation = phase39_environment_observation()
    if (observation["production_gates_approved"] != 0
            or observation["production_dispatch_allowed"]
            or observation["iso_release_allowed"]):
        raise AssertionError(
            "Phase 39 local observation promoted a production gate")
    return {
        "status": STATUS,
        "contract_digest": phase39_contract_digest(),
        "job_schema_sha256": hashlib.sha256(
            canonical_json_bytes(gate_job_schema())).hexdigest(),
        "result_schema_sha256": hashlib.sha256(
            canonical_json_bytes(gate_result_schema())).hexdigest(),
        "negative_cases_rejected": negative["rejected_count"],
        "production_gates_approved": 0,
        "production_dispatch_allowed": False,
        "iso_release_allowed": False,
    }
