def _digest(domain: bytes, value: Mapping[str, Any]) -> str:
    return hashlib.sha256(domain + canonical_json_bytes(value)).hexdigest()


def _sha256(value: Any, context: str) -> str:
    if type(value) is not str or not _HEX64.fullmatch(value):
        raise PolicyError(f"{context} must be a lowercase SHA-256 digest")
    return value


def _fingerprint(value: Any, context: str) -> str:
    if type(value) is not str or not _FINGERPRINT.fullmatch(value):
        raise PolicyError(f"{context} must be an uppercase 40-hex fingerprint")
    return value


def _token(value: Any, context: str) -> str:
    if type(value) is not str or not _TOKEN.fullmatch(value):
        raise PolicyError(f"{context} is not a safe token")
    return value


def _safe_argv(value: Any, context: str) -> list[str]:
    if type(value) is not list or not 1 <= len(value) <= 128:
        raise PolicyError(f"{context} argv length is invalid")
    argv: list[str] = []
    total = 0
    for item in value:
        if (type(item) is not str or not item or len(item) > 4096
                or "\x00" in item
                or any(ord(ch) < 32 and ch != "\t" for ch in item)):
            raise PolicyError(f"{context} argv contains an unsafe value")
        total += len(item.encode("utf-8"))
        argv.append(item)
    if total > 64 * 1024:
        raise PolicyError(f"{context} argv is too large")
    executable = Path(argv[0])
    if (not executable.is_absolute()
            or executable.name.lower() in SHELL_EXECUTABLES):
        raise PolicyError(
            f"{context} must use an absolute non-shell executable")
    return argv


def create_command(
    *, sequence: int, argv: Sequence[str], timeout_seconds: int = 3600,
    network_allowed: bool = False,
    working_directory_label: str = "isolated-work-root",
) -> dict[str, Any]:
    if type(sequence) is not int or not 1 <= sequence <= MAX_COMMANDS:
        raise PolicyError("Phase 39 command sequence is invalid")
    checked_argv = _safe_argv(list(argv), "Phase 39 command")
    if (type(timeout_seconds) is not int
            or not 1 <= timeout_seconds <= 24 * 60 * 60):
        raise PolicyError("Phase 39 command timeout is invalid")
    if type(network_allowed) is not bool:
        raise PolicyError("Phase 39 command network flag is invalid")
    label = _token(working_directory_label,
                   "Phase 39 working-directory label")
    unsigned = {
        "sequence": sequence,
        "argv": checked_argv,
        "timeout_seconds": timeout_seconds,
        "network_allowed": network_allowed,
        "working_directory_label": label,
        "shell_allowed": False,
    }
    return {**unsigned, "command_digest": _digest(COMMAND_DOMAIN, unsigned)}


def _parse_command(
    value: Mapping[str, Any], *, expected_sequence: int,
    network_policy: str,
) -> dict[str, Any]:
    fields = {
        "sequence", "argv", "timeout_seconds", "network_allowed",
        "working_directory_label", "shell_allowed", "command_digest",
    }
    if type(value) is not dict or set(value) != fields:
        raise PolicyError("Phase 39 command fields are not closed")
    if value["sequence"] != expected_sequence:
        raise PolicyError("Phase 39 command sequence is not contiguous")
    if value["shell_allowed"] is not False:
        raise PolicyError("Phase 39 shell execution is forbidden")
    if type(value["network_allowed"]) is not bool:
        raise PolicyError("Phase 39 command network flag is invalid")
    if (network_policy in {"offline", "isolated"}
            and value["network_allowed"]):
        raise PolicyError(
            "Phase 39 command violates the gate network policy")
    expected = create_command(
        sequence=expected_sequence,
        argv=_safe_argv(value["argv"], "Phase 39 command"),
        timeout_seconds=value["timeout_seconds"],
        network_allowed=value["network_allowed"],
        working_directory_label=value["working_directory_label"],
    )
    if value != expected:
        raise PolicyError("Phase 39 command digest or fields drifted")
    return expected


